#[test]
fn test_generated_rs_runtime_parity() {
    let root = workspace_root();
    let toml_path = root.join("catalog/commands.toml");
    let catalog = CommandCatalog::load_file(&toml_path).expect("load commands.toml");

    assert_eq!(
        mathslot_command::generated::GENERATED_COMMANDS.len(),
        catalog.commands.len(),
        "GENERATED_COMMANDS length must match catalog commands count"
    );

    for cmd in &catalog.commands {
        let static_cmd = mathslot_command::generated::find_by_id(&cmd.id)
            .unwrap_or_else(|| panic!("Command '{}' not found in GENERATED_COMMANDS", cmd.id));

        assert_eq!(static_cmd.id, cmd.id);
        assert_eq!(static_cmd.label, cmd.label);
        assert_eq!(static_cmd.category, cmd.category);
        assert_eq!(static_cmd.glyph, cmd.glyph);
        assert_eq!(static_cmd.latex, cmd.latex);
        assert_eq!(static_cmd.doc, cmd.doc);
        assert_eq!(static_cmd.is_default, cmd.is_default);
        assert_eq!(static_cmd.wrap_body_slot, cmd.wrap_body_slot);

        let keys_vec: Vec<&str> = static_cmd.keys.to_vec();
        assert_eq!(keys_vec, cmd.keys);

        let slots_vec: Vec<&str> = static_cmd.slots.to_vec();
        assert_eq!(slots_vec, cmd.slots);

        let ex_vec: Vec<&str> = static_cmd.examples.to_vec();
        assert_eq!(ex_vec, cmd.examples);

        let by_keys = mathslot_command::generated::find_by_keys(static_cmd.keys);
        assert_eq!(
            by_keys.map(|c| c.id),
            Some(cmd.id.as_str()),
            "find_by_keys failed for command '{}'",
            cmd.id
        );
    }

    for &cat in mathslot_command::ALLOWED_CATEGORIES {
        let gen_cat: Vec<_> = mathslot_command::generated::by_category(cat).collect();
        let cat_expected = catalog.by_category(cat);
        assert_eq!(
            gen_cat.len(),
            cat_expected.len(),
            "Category '{}' command count mismatch",
            cat
        );
    }
}

