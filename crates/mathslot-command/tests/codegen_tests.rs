#[test]
fn test_catalog_ts_parity() {
    let root = workspace_root();
    let toml_path = root.join("catalog/commands.toml");
    let ts_path = root.join("packages/ui/src/generated/catalog.ts");

    let catalog = CommandCatalog::load_file(&toml_path).expect("load commands.toml");
    let ts_content = std::fs::read_to_string(&ts_path).unwrap_or_else(|e| {
        panic!("Failed to read catalog.ts: {}", e);
    });

    assert!(
        ts_content.contains("export interface CommandEntry"),
        "catalog.ts must export CommandEntry interface"
    );
    assert!(
        ts_content.contains("export const COMMANDS: readonly CommandEntry[] = ["),
        "catalog.ts must export COMMANDS array"
    );
    assert!(
        ts_content
            .contains("export const COMMANDS_BY_ID: Readonly<Record<string, CommandEntry>> = {"),
        "catalog.ts must export COMMANDS_BY_ID dictionary"
    );

    for cmd in &catalog.commands {
        let needle = format!("id: \"{}\"", cmd.id);
        let needle_quoted = format!("\"id\": \"{}\"", cmd.id);
        let map_needle = format!("\"{}\": {{", cmd.id);
        let map_needle_unquoted = format!("{}: {{", cmd.id);
        assert!(
            ts_content.contains(&needle)
                || ts_content.contains(&needle_quoted)
                || ts_content.contains(&map_needle)
                || ts_content.contains(&map_needle_unquoted),
            "catalog.ts missing command id '{}'",
            cmd.id
        );
    }
}

