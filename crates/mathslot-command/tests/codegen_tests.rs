use mathslot_command::CommandCatalog;
use std::path::PathBuf;

fn workspace_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("crates/ dir")
        .parent()
        .expect("repo root dir")
        .to_path_buf()
}

const ARTIFACT_PATHS: &[&str] = &[
    "crates/mathslot-command/src/generated.rs",
    "catalog/catalog.json",
    "docs/commands.md",
    "packages/ui/src/generated/catalog.ts",
    "schemas/commands.schema.json",
];

#[test]
fn test_artifacts_exist_and_not_empty() {
    let root = workspace_root();
    for rel_path in ARTIFACT_PATHS {
        let p = root.join(rel_path);
        assert!(
            p.exists(),
            "Required artifact '{}' does not exist at '{}'. Run 'cargo run -p xtask -- generate'.",
            rel_path,
            p.display()
        );
        let meta = std::fs::metadata(&p).expect("read metadata");
        assert!(meta.len() > 0, "Artifact '{}' must not be empty", rel_path);
    }
}

#[test]
fn test_artifacts_contain_generated_banner() {
    let root = workspace_root();
    for rel_path in ARTIFACT_PATHS {
        let p = root.join(rel_path);
        let content = std::fs::read_to_string(&p).unwrap_or_else(|e| {
            panic!("Failed to read artifact '{}': {}", rel_path, e);
        });
        assert!(
            content.contains("@generated by xtask. DO NOT EDIT."),
            "Artifact '{}' must contain '@generated by xtask. DO NOT EDIT.' header banner",
            rel_path
        );
        assert!(
            !content.contains("\r\n"),
            "Artifact '{}' must use Unix LF line endings, but CRLF was found",
            rel_path
        );
        assert!(
            content.ends_with('\n'),
            "Artifact '{}' must end with a single newline character",
            rel_path
        );
    }
}

#[test]
fn test_catalog_json_parity() {
    let root = workspace_root();
    let toml_path = root.join("catalog/commands.toml");
    let json_path = root.join("catalog/catalog.json");

    let catalog = CommandCatalog::load_file(&toml_path).expect("load commands.toml");
    let json_content = std::fs::read_to_string(&json_path).unwrap_or_else(|e| {
        panic!("Failed to read catalog.json: {}", e);
    });

    assert!(
        json_content.contains("\"commands\": ["),
        "catalog.json must contain commands array"
    );

    for cmd in &catalog.commands {
        let id_needle = format!("\"id\": \"{}\"", cmd.id);
        assert!(
            json_content.contains(&id_needle),
            "catalog.json missing command id '{}'",
            cmd.id
        );
        let label_needle = format!("\"label\": \"{}\"", cmd.label);
        assert!(
            json_content.contains(&label_needle),
            "catalog.json missing command label '{}'",
            cmd.label
        );
    }
}

