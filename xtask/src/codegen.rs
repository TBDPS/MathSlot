#[derive(Debug, Clone)]
pub struct WorkspaceMetadata {
    pub version: String,
    pub license: String,
    pub workspace_members: Vec<String>,
    pub obsidian_version: String,
    pub obsidian_min_app_version: String,
    pub library_schema_version: u32,
    pub default_shortcuts: BTreeMap<String, String>,
}

pub fn load_workspace_metadata(
    root: &Path,
) -> Result<WorkspaceMetadata, Box<dyn std::error::Error>> {
    let cargo_toml_raw = std::fs::read_to_string(root.join("Cargo.toml"))?;
    let cargo_val: toml::Value = toml::from_str(&cargo_toml_raw)?;

    let pkg = cargo_val
        .get("workspace")
        .and_then(|w| w.get("package"))
        .ok_or("Cargo.toml missing [workspace.package]")?;
    let version = pkg
        .get("version")
        .and_then(toml::Value::as_str)
        .ok_or("Cargo.toml missing workspace.package.version")?
        .to_string();
    let license = pkg
        .get("license")
        .and_then(toml::Value::as_str)
        .ok_or("Cargo.toml missing workspace.package.license")?
        .to_string();
    let workspace_members = cargo_val
        .get("workspace")
        .and_then(|w| w.get("members"))
        .and_then(toml::Value::as_array)
        .ok_or("Cargo.toml missing workspace.members")?
        .iter()
        .filter_map(toml::Value::as_str)
        .map(ToString::to_string)
        .collect::<Vec<_>>();

    let manifest_raw = std::fs::read_to_string(root.join("obsidian-mathslot/manifest.json"))?;
    let manifest_val: serde_json::Value = serde_json::from_str(&manifest_raw)?;
    let obsidian_version = manifest_val
        .get("version")
        .and_then(serde_json::Value::as_str)
        .ok_or("obsidian-mathslot/manifest.json missing version")?
        .to_string();
    let obsidian_min_app_version = manifest_val
        .get("minAppVersion")
        .and_then(serde_json::Value::as_str)
        .ok_or("obsidian-mathslot/manifest.json missing minAppVersion")?
        .to_string();

    let store_lib_raw = std::fs::read_to_string(root.join("crates/mathslot-store/src/lib.rs"))?;
    let library_schema_version = parse_schema_version(&store_lib_raw)?;
    let default_shortcuts = parse_default_shortcuts(&store_lib_raw)?;

    Ok(WorkspaceMetadata {
        version,
        license,
        workspace_members,
        obsidian_version,
        obsidian_min_app_version,
        library_schema_version,
        default_shortcuts,
    })
}

fn parse_schema_version(store_lib_raw: &str) -> Result<u32, Box<dyn std::error::Error>> {
    for line in store_lib_raw.lines() {
        let trimmed = line.trim();
        if let Some(rest) = trimmed.strip_prefix("pub const CURRENT_LIBRARY_SCHEMA_VERSION: u32 =")
            && let Some(num_str) = rest.trim().strip_suffix(';')
        {
            return Ok(num_str.trim().parse::<u32>()?);
        }
    }
    Err("CURRENT_LIBRARY_SCHEMA_VERSION not found in crates/mathslot-store/src/lib.rs".into())
}

fn parse_default_shortcuts(
    store_lib_raw: &str,
) -> Result<BTreeMap<String, String>, Box<dyn std::error::Error>> {
    let required_keys = [
        "nav_next_slot",
        "nav_prev_slot",
        "nav_parent",
        "nav_first_child",
        "copy_latex",
        "save_snippet",
        "focus_editor",
        "toggle_nav",
        "open_settings",
    ];
    let mut map = BTreeMap::new();
    let lines: Vec<&str> = store_lib_raw.lines().collect();

    for (idx, line) in lines.iter().enumerate() {
        let trimmed = line.trim();
        if let Some(rest) = trimmed.strip_prefix("fn default_")
            && let Some(fn_name) = rest.strip_suffix("() -> String {")
            && required_keys.contains(&fn_name)
            && let Some(body_line) = lines.get(idx + 1)
        {
            let body_trimmed = body_line.trim();
            if let Some(quoted) = body_trimmed.strip_suffix(".to_owned()")
                && quoted.starts_with('"')
                && quoted.ends_with('"')
                && quoted.len() >= 2
            {
                let val = serde_json::from_str::<String>(quoted)?;
                map.insert(fn_name.to_string(), val);
            }
        }
    }

    for key in required_keys {
        if !map.contains_key(key) {
            return Err(format!(
                "default shortcut '{key}' not found in crates/mathslot-store/src/lib.rs"
            )
            .into());
        }
    }

    Ok(map)
}

pub fn render_metadata_block(
    meta: &WorkspaceMetadata,
    catalog: &CommandCatalog,
    presets_file: &PresetsFile,
    include_workspace_members: bool,
) -> String {
    let mut preset_categories: Vec<&str> = Vec::new();
    for preset in &presets_file.presets {
        if !preset_categories.contains(&preset.category.as_str()) {
            preset_categories.push(preset.category.as_str());
        }
    }

    let mut out = String::new();
    out.push_str("| 指标 | 当前权威值 | 唯一事实源 (SSOT) |\n");
    out.push_str("| :--- | :--- | :--- |\n");
    out.push_str(&format!(
        "| **工作区 / 桌面端版本** | `{}` | `Cargo.toml` (`[workspace.package].version`) |\n",
        meta.version
    ));
    out.push_str(&format!(
        "| **Obsidian 插件版本** | `{}` (Obsidian ≥ `{}`) | `obsidian-mathslot/manifest.json` |\n",
        meta.obsidian_version, meta.obsidian_min_app_version
    ));
    out.push_str(&format!(
        "| **开源协议** | `{}` | `Cargo.toml` (`[workspace.package].license`) |\n",
        meta.license
    ));
    out.push_str(&format!(
        "| **流式命令总数** | `{}` 条 / `{}` 大分类 | `catalog/commands.toml` |\n",
        catalog.commands.len(),
        ALLOWED_CATEGORIES.len()
    ));
    out.push_str(&format!(
        "| **内置预置公式** | `{}` 条 / `{}` 大分类 | `catalog/presets.json` |\n",
        presets_file.presets.len(),
        preset_categories.len()
    ));
    out.push_str(&format!(
        "| **配置库 Schema 版本** | `schema_version = {}` | `crates/mathslot-store/src/lib.rs` |\n",
        meta.library_schema_version
    ));

    if include_workspace_members {
        let members_list = meta
            .workspace_members
            .iter()
            .map(|m| format!("`{m}`"))
            .collect::<Vec<_>>()
            .join("、");
        out.push_str(&format!(
            "\n- **Workspace 成员包（{} 个）**：{}\n",
            meta.workspace_members.len(),
            members_list
        ));
        out.push_str(
            "- **`xtask` 生成产物（6 份代码/数据 + 4 份文档注入块）**：`crates/mathslot-command/src/generated.rs`、`catalog/catalog.json`、`docs/commands.md`、`packages/ui/src/generated/catalog.ts`、`packages/ui/src/generated/presets.ts`、`schemas/commands.schema.json`，以及 `README.md`、`HELP.md`、`obsidian-mathslot/README.md`、`docs/ARCHITECTURE.md` 中的 `BEGIN/END GENERATED` 锚点块。",
        );
    }

    out.trim_end().to_string()
}

