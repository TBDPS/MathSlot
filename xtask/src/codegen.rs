pub fn render_commands_tables(catalog: &CommandCatalog, heading_prefix: &str) -> String {
    let mut out = String::new();

    let categories = [
        ("structure", "直达结构 (structure)"),
        ("calculus", "微积分 (calculus)"),
        ("matrix", "矩阵 (matrix)"),
        ("accent", "装饰 (accent)"),
        ("greek", "希腊字母 (greek)"),
        ("symbol", "数学符号 (symbol)"),
        ("relation", "关系符号 (relation)"),
        ("setlogic", "集合与逻辑 (setlogic)"),
    ];

    for (cat_id, cat_title) in categories {
        let items: Vec<&CommandEntry> = catalog
            .commands
            .iter()
            .filter(|c| c.category == cat_id)
            .collect();
        if items.is_empty() {
            continue;
        }

        out.push_str(&format!("{}{}\n\n", heading_prefix, cat_title));
        out.push_str(
            "| 简码 (ID) | 按键序列 | 显示标签 | 字符 | 槽位 | LaTeX 模板 | 示例 | 说明 |\n",
        );
        out.push_str("| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n");

        for item in items {
            let keys_disp = format!("`▸{}`", item.keys.join(""));
            let glyph_escaped = item.glyph.replace('|', "\\|");
            let slots_disp = if item.slots.is_empty() {
                "-".to_string()
            } else {
                item.slots.join(", ")
            };
            let latex_escaped = item.latex.replace('|', "\\|");
            let examples_disp = item
                .examples
                .iter()
                .map(|e| format!("`{}`", e))
                .collect::<Vec<_>>()
                .join(", ");
            let doc_escaped = item.doc.replace('|', "\\|");

            out.push_str(&format!(
                "| `{}` | {} | {} | {} | {} | `{}` | {} | {} |\n",
                item.id,
                keys_disp,
                item.label,
                glyph_escaped,
                slots_disp,
                latex_escaped,
                examples_disp,
                doc_escaped
            ));
        }
        out.push('\n');
    }

    out
}

pub fn generate_typescript(catalog: &CommandCatalog) -> String {
    let mut out = String::new();
    out.push_str("// @generated by xtask. DO NOT EDIT.\n\n");
    out.push_str("export type CommandCategory =\n");
    for cat in ALLOWED_CATEGORIES {
        out.push_str(&format!("  | \"{}\"\n", cat));
    }
    out.push_str(";\n\n");

    out.push_str("export interface CommandEntry {\n");
    out.push_str("  id: string;\n");
    out.push_str("  keys: readonly string[];\n");
    out.push_str("  label: string;\n");
    out.push_str("  category: CommandCategory;\n");
    out.push_str("  glyph: string;\n");
    out.push_str("  slots: readonly string[];\n");
    out.push_str("  latex: string;\n");
    out.push_str("  doc: string;\n");
    out.push_str("  examples: readonly string[];\n");
    out.push_str("  is_default?: boolean;\n");
    out.push_str("  wrap_body_slot?: number;\n");
    out.push_str("}\n\n");

    out.push_str("export const COMMANDS: readonly CommandEntry[] = [\n");
    for cmd in &catalog.commands {
        out.push_str("  {\n");
        out.push_str(&format!("    id: {:?},\n", cmd.id));

        let keys_json = serde_json::to_string(&cmd.keys).unwrap();
        out.push_str(&format!("    keys: {},\n", keys_json));

        out.push_str(&format!("    label: {:?},\n", cmd.label));
        out.push_str(&format!("    category: {:?},\n", cmd.category));
        out.push_str(&format!("    glyph: {:?},\n", cmd.glyph));

        let slots_json = serde_json::to_string(&cmd.slots).unwrap();
        out.push_str(&format!("    slots: {},\n", slots_json));

        out.push_str(&format!("    latex: {:?},\n", cmd.latex));
        out.push_str(&format!("    doc: {:?},\n", cmd.doc));

        let ex_json = serde_json::to_string(&cmd.examples).unwrap();
        out.push_str(&format!("    examples: {},\n", ex_json));

        if cmd.is_default {
            out.push_str("    is_default: true,\n");
        }
        if let Some(wrap) = cmd.wrap_body_slot {
            out.push_str(&format!("    wrap_body_slot: {},\n", wrap));
        }
        out.push_str("  },\n");
    }
    out.push_str("];\n\n");

    out.push_str("export const COMMANDS_BY_ID: Readonly<Record<string, CommandEntry>> = {\n");
    for (i, cmd) in catalog.commands.iter().enumerate() {
        out.push_str(&format!("  {:?}: COMMANDS[{}],\n", cmd.id, i));
    }
    out.push_str("};\n");

    out
}

pub fn generate_presets_typescript(
    presets_file: &PresetsFile,
) -> Result<String, Box<dyn std::error::Error>> {
    if presets_file.schema_version != 1 {
        return Err(format!(
            "unsupported presets.json schema_version: {}",
            presets_file.schema_version
        )
        .into());
    }

    let mut categories: Vec<&str> = Vec::new();
    for preset in &presets_file.presets {
        if !categories.contains(&preset.category.as_str()) {
            categories.push(preset.category.as_str());
        }
    }

    let mut out = String::new();
    out.push_str("// @generated by xtask. DO NOT EDIT.\n\n");
    out.push_str("export const PRESET_CATEGORIES = [\n");
    for cat in &categories {
        let cat_json = serde_json::to_string(cat)?;
        out.push_str(&format!("  {cat_json},\n"));
    }
    out.push_str("] as const;\n\n");
    out.push_str("export type PresetCategory = (typeof PRESET_CATEGORIES)[number];\n\n");

    out.push_str("export interface PresetEntry {\n");
    out.push_str("  id: string;\n");
    out.push_str("  legacy_id: string;\n");
    out.push_str("  category: PresetCategory;\n");
    out.push_str("  name: string;\n");
    out.push_str("  source: string;\n");
    out.push_str("  desc: string;\n");
    out.push_str("  tags: readonly string[];\n");
    out.push_str("}\n\n");

    out.push_str("export const PRESETS: readonly PresetEntry[] = [\n");
    for preset in &presets_file.presets {
        out.push_str("  {\n");
        out.push_str(&format!(
            "    id: {},\n",
            serde_json::to_string(&preset.id)?
        ));
        out.push_str(&format!(
            "    legacy_id: {},\n",
            serde_json::to_string(&preset.legacy_id)?
        ));
        out.push_str(&format!(
            "    category: {},\n",
            serde_json::to_string(&preset.category)?
        ));
        out.push_str(&format!(
            "    name: {},\n",
            serde_json::to_string(&preset.name)?
        ));
        out.push_str(&format!(
            "    source: {},\n",
            serde_json::to_string(&preset.source)?
        ));
        out.push_str(&format!(
            "    desc: {},\n",
            serde_json::to_string(&preset.desc)?
        ));
        out.push_str(&format!(
            "    tags: {},\n",
            serde_json::to_string(&preset.tags)?
        ));
        out.push_str("  },\n");
    }
    out.push_str("];\n\n");

    out.push_str("export const PRESETS_BY_ID: Readonly<Record<string, PresetEntry>> = {\n");
    for (i, preset) in presets_file.presets.iter().enumerate() {
        out.push_str(&format!(
            "  {}: PRESETS[{}],\n",
            serde_json::to_string(&preset.id)?,
            i
        ));
    }
    out.push_str("};\n");

    Ok(out)
}

