pub fn render_presets_block(presets_file: &PresetsFile) -> String {
    let mut ordered_cats: Vec<(&str, Vec<&PresetJsonEntry>)> = Vec::new();
    for preset in &presets_file.presets {
        if let Some((_, list)) = ordered_cats
            .iter_mut()
            .find(|(c, _)| *c == preset.category.as_str())
        {
            list.push(preset);
        } else {
            ordered_cats.push((preset.category.as_str(), vec![preset]));
        }
    }

    let mut out = String::new();
    out.push_str(&format!(
        "> 由 `xtask` 根据 `catalog/presets.json` 自动生成：共 **`{}`** 条权威公式，覆盖 **`{}`** 大分类。\n\n",
        presets_file.presets.len(),
        ordered_cats.len()
    ));
    out.push_str("| 序号 | 分类 | 条目数 | 代表公式示例 |\n");
    out.push_str("| :--- | :--- | :---: | :--- |\n");
    for (idx, (cat, items)) in ordered_cats.iter().enumerate() {
        let samples = items
            .iter()
            .take(3)
            .map(|p| p.name.as_str())
            .collect::<Vec<_>>()
            .join("、");
        out.push_str(&format!(
            "| {} | **{}** | {} | {} |\n",
            idx + 1,
            cat,
            items.len(),
            samples
        ));
    }
    out.trim_end().to_string()
}

