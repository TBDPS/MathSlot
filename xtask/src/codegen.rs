use mathslot_command::{ALLOWED_CATEGORIES, CommandCatalog, CommandEntry};
use serde::Serialize;

#[derive(Serialize)]
struct CatalogJsonOutput<'a> {
    #[serde(rename = "$comment")]
    comment: &'static str,
    commands: &'a [CommandEntry],
}

pub fn generate_rust(catalog: &CommandCatalog) -> String {
    let mut out = String::new();
    out.push_str("// @generated by xtask. DO NOT EDIT.\n\n");
    out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n");
    out.push_str("pub struct StaticCommand {\n");
    out.push_str("    pub id: &'static str,\n");
    out.push_str("    pub keys: &'static [&'static str],\n");
    out.push_str("    pub label: &'static str,\n");
    out.push_str("    pub category: &'static str,\n");
    out.push_str("    pub glyph: &'static str,\n");
    out.push_str("    pub slots: &'static [&'static str],\n");
    out.push_str("    pub latex: &'static str,\n");
    out.push_str("    pub doc: &'static str,\n");
    out.push_str("    pub examples: &'static [&'static str],\n");
    out.push_str("    pub is_default: bool,\n");
    out.push_str("    pub wrap_body_slot: Option<usize>,\n");
    out.push_str("}\n\n");

    for cmd in &catalog.commands {
        let const_name = format!("CMD_{}", cmd.id.to_uppercase());
        out.push_str(&format!(
            "pub const {}: StaticCommand = StaticCommand {{\n",
            const_name
        ));
        out.push_str(&format!("    id: {:?},\n", cmd.id));

        let keys_str = cmd
            .keys
            .iter()
            .map(|k| format!("{:?}", k))
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!("    keys: &[{}],\n", keys_str));

        out.push_str(&format!("    label: {:?},\n", cmd.label));
        out.push_str(&format!("    category: {:?},\n", cmd.category));
        out.push_str(&format!("    glyph: {:?},\n", cmd.glyph));

        let slots_str = cmd
            .slots
            .iter()
            .map(|s| format!("{:?}", s))
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!("    slots: &[{}],\n", slots_str));

        out.push_str(&format!("    latex: {:?},\n", cmd.latex));
        out.push_str(&format!("    doc: {:?},\n", cmd.doc));

        let ex_str = cmd
            .examples
            .iter()
            .map(|e| format!("{:?}", e))
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!("    examples: &[{}],\n", ex_str));

        out.push_str(&format!("    is_default: {},\n", cmd.is_default));
        match cmd.wrap_body_slot {
            Some(w) => out.push_str(&format!("    wrap_body_slot: Some({}),\n", w)),
            None => out.push_str("    wrap_body_slot: None,\n"),
        }
        out.push_str("};\n\n");
    }

    out.push_str("pub static GENERATED_COMMANDS: &[StaticCommand] = &[\n");
    for cmd in &catalog.commands {
        let const_name = format!("CMD_{}", cmd.id.to_uppercase());
        out.push_str(&format!("    {},\n", const_name));
    }
    out.push_str("];\n\n");

    out.push_str("#[must_use]\n");
    out.push_str("pub fn find_by_id(id: &str) -> Option<&'static StaticCommand> {\n");
    out.push_str("    GENERATED_COMMANDS.iter().find(|cmd| cmd.id == id)\n");
    out.push_str("}\n\n");

    out.push_str("#[must_use]\n");
    out.push_str("pub fn find_by_keys(keys: &[&str]) -> Option<&'static StaticCommand> {\n");
    out.push_str("    GENERATED_COMMANDS.iter().find(|cmd| cmd.keys == keys)\n");
    out.push_str("}\n\n");

    out.push_str(
        "pub fn by_category(category: &str) -> impl Iterator<Item = &'static StaticCommand> {\n",
    );
    out.push_str("    GENERATED_COMMANDS\n");
    out.push_str("        .iter()\n");
    out.push_str("        .filter(move |cmd| cmd.category == category)\n");
    out.push_str("}\n");

    format_rust(&out)
}

fn format_rust(code: &str) -> String {
    use std::io::Write;
    use std::process::{Command, Stdio};

    if let Ok(mut child) = Command::new("rustfmt")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
    {
        if let Some(mut stdin) = child.stdin.take() {
            let _ = stdin.write_all(code.as_bytes());
        }
        if let Ok(output) = child.wait_with_output()
            && output.status.success()
            && let Ok(formatted) = String::from_utf8(output.stdout)
        {
            return formatted;
        }
    }
    code.to_string()
}

pub fn generate_json(catalog: &CommandCatalog) -> String {
    let output = CatalogJsonOutput {
        comment: "@generated by xtask. DO NOT EDIT.",
        commands: &catalog.commands,
    };
    let mut s = serde_json::to_string_pretty(&output).expect("serialize catalog.json");
    s.push('\n');
    s
}

pub fn generate_markdown(catalog: &CommandCatalog) -> String {
    let mut out = String::new();
    out.push_str("<!-- @generated by xtask. DO NOT EDIT. -->\n\n");
    out.push_str("# MathSlot 命令目录 (Commands Catalog)\n\n");
    out.push_str("> 本文档由 `xtask` 根据 `catalog/commands.toml` 自动生成，禁止手动修改。\n\n");

    let categories = [
        ("structure", "直达结构 (structure)"),
        ("calculus", "微积分 (calculus)"),
        ("matrix", "矩阵 (matrix)"),
        ("accent", "装饰 (accent)"),
        ("greek", "希腊字母 (greek)"),
        ("symbol", "数学符号 (symbol)"),
        ("relation", "关系符号 (relation)"),
        ("setlogic", "集合与逻辑 (setlogic)"),
    ];

    for (cat_id, cat_title) in categories {
        let items: Vec<&CommandEntry> = catalog
            .commands
            .iter()
            .filter(|c| c.category == cat_id)
            .collect();
        if items.is_empty() {
            continue;
        }

        out.push_str(&format!("## {}\n\n", cat_title));
        out.push_str(
            "| 简码 (ID) | 按键序列 | 显示标签 | 字符 | 槽位 | LaTeX 模板 | 示例 | 说明 |\n",
        );
        out.push_str("| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n");

        for item in items {
            let keys_disp = format!("`▸{}`", item.keys.join(""));
            let glyph_escaped = item.glyph.replace('|', "\\|");
            let slots_disp = if item.slots.is_empty() {
                "-".to_string()
            } else {
                item.slots.join(", ")
            };
            let latex_escaped = item.latex.replace('|', "\\|");
            let examples_disp = item
                .examples
                .iter()
                .map(|e| format!("`{}`", e))
                .collect::<Vec<_>>()
                .join(", ");
            let doc_escaped = item.doc.replace('|', "\\|");

            out.push_str(&format!(
                "| `{}` | {} | {} | {} | {} | `{}` | {} | {} |\n",
                item.id,
                keys_disp,
                item.label,
                glyph_escaped,
                slots_disp,
                latex_escaped,
                examples_disp,
                doc_escaped
            ));
        }
        out.push('\n');
    }

    out
}

pub fn generate_typescript(catalog: &CommandCatalog) -> String {
    let mut out = String::new();
    out.push_str("// @generated by xtask. DO NOT EDIT.\n\n");
    out.push_str("export type CommandCategory =\n");
    for cat in ALLOWED_CATEGORIES {
        out.push_str(&format!("  | \"{}\"\n", cat));
    }
    out.push_str(";\n\n");

    out.push_str("export interface CommandEntry {\n");
    out.push_str("  id: string;\n");
    out.push_str("  keys: readonly string[];\n");
    out.push_str("  label: string;\n");
    out.push_str("  category: CommandCategory;\n");
    out.push_str("  glyph: string;\n");
    out.push_str("  slots: readonly string[];\n");
    out.push_str("  latex: string;\n");
    out.push_str("  doc: string;\n");
    out.push_str("  examples: readonly string[];\n");
    out.push_str("  is_default?: boolean;\n");
    out.push_str("  wrap_body_slot?: number;\n");
    out.push_str("}\n\n");

    out.push_str("export const COMMANDS: readonly CommandEntry[] = [\n");
    for cmd in &catalog.commands {
        out.push_str("  {\n");
        out.push_str(&format!("    id: {:?},\n", cmd.id));

        let keys_json = serde_json::to_string(&cmd.keys).unwrap();
        out.push_str(&format!("    keys: {},\n", keys_json));

        out.push_str(&format!("    label: {:?},\n", cmd.label));
        out.push_str(&format!("    category: {:?},\n", cmd.category));
        out.push_str(&format!("    glyph: {:?},\n", cmd.glyph));

        let slots_json = serde_json::to_string(&cmd.slots).unwrap();
        out.push_str(&format!("    slots: {},\n", slots_json));

        out.push_str(&format!("    latex: {:?},\n", cmd.latex));
        out.push_str(&format!("    doc: {:?},\n", cmd.doc));

        let ex_json = serde_json::to_string(&cmd.examples).unwrap();
        out.push_str(&format!("    examples: {},\n", ex_json));

        if cmd.is_default {
            out.push_str("    is_default: true,\n");
        }
        if let Some(wrap) = cmd.wrap_body_slot {
            out.push_str(&format!("    wrap_body_slot: {},\n", wrap));
        }
        out.push_str("  },\n");
    }
    out.push_str("];\n\n");

    out.push_str("export const COMMANDS_BY_ID: Readonly<Record<string, CommandEntry>> = {\n");
    for (i, cmd) in catalog.commands.iter().enumerate() {
        out.push_str(&format!("  {:?}: COMMANDS[{}],\n", cmd.id, i));
    }
    out.push_str("};\n");

    out
}

