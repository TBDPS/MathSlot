pub fn inject_generated_blocks(
    doc_path: &str,
    original: &str,
    blocks: &[(&str, String)],
) -> Result<String, Box<dyn std::error::Error>> {
    let mut updated = original.replace("\r\n", "\n");
    for (name, body) in blocks {
        let begin_marker = format!("<!-- BEGIN GENERATED: {name} -->");
        let end_marker = format!("<!-- END GENERATED: {name} -->");

        let begin_matches: Vec<_> = updated.match_indices(&begin_marker).collect();
        let end_matches: Vec<_> = updated.match_indices(&end_marker).collect();
        if begin_matches.len() != 1 || end_matches.len() != 1 {
            return Err(format!(
                "Document '{doc_path}' must contain exactly one '{begin_marker}' and one '{end_marker}'"
            )
            .into());
        }

        let begin_pos = begin_matches[0].0;
        let end_pos = end_matches[0].0;
        let after_begin = begin_pos + begin_marker.len();
        if end_pos < after_begin {
            return Err(format!(
                "Document '{doc_path}' has '{end_marker}' before '{begin_marker}'"
            )
            .into());
        }

        let replacement = format!("{begin_marker}\n{}\n{end_marker}", body.trim_matches('\n'));
        updated.replace_range(begin_pos..end_pos + end_marker.len(), &replacement);
    }

    if !updated.ends_with('\n') {
        updated.push('\n');
    }
    Ok(updated)
}
